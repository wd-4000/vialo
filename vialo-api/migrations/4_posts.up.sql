-- Bulletin board
--
CREATE TYPE post_visibility AS ENUM('public', 'logged_in', 'board');

CREATE TABLE boards (
  id int PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  label int NOT NULL REFERENCES i18n_index (id),
  slug citext UNIQUE NOT NULL,
  icon citext,
  group_id uuid REFERENCES account_groups (id) ON DELETE CASCADE, -- Linked group id (optional)
  default_post_visibility post_visibility NOT NULL default 'board',
  system bool NOT NULL DEFAULT false
);

