CREATE TYPE board_perm AS ENUM('view', 'post', 'moderate', 'admin');

CREATE TABLE board_group_perms (
  id int PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  group_id uuid REFERENCES account_groups (id) ON DELETE CASCADE,
  board_id int NOT NULL REFERENCES boards (id) ON DELETE CASCADE,
  perm board_perm NOT NULL,
  UNIQUE NULLS NOT DISTINCT (group_id, board_id)
);

CREATE TABLE board_posts (
  id int PRIMARY KEY GENERATED ALWAYS AS IDENTITY,
  account_id uuid REFERENCES accounts_people (id) ON DELETE CASCADE, -- TODO: Maybe app should handle transfering some posts to others or implement posts owned by groups
  board_id int NOT NULL REFERENCES boards (id) ON DELETE CASCADE,
  icon text,
  title int REFERENCES i18n_index (id),
  content int REFERENCES i18n_index (id),
  content_html int REFERENCES i18n_index (id),
  content_plain int REFERENCES i18n_index (id),
  location int REFERENCES i18n_index (id),
  event_from timestamptz,
  event_to timestamptz,
  created_at timestamptz NOT NULL default NOW(),
  visibility post_visibility not null default 'board'
);

CREATE INDEX board_posts_event_idx ON board_posts (event_from, event_to);

CREATE INDEX board_posts_created_at_idx ON board_posts (created_at);

CREATE INDEX board_posts_board_id_idx ON board_posts (board_id);

CREATE INDEX board_posts_account_id_idx ON board_posts (account_id);

